#!/usr/bin/env node
/*
 * build_screens.mjs - assemble the click-dummy app into `out/`.
 *
 * Input:
 *   wireframes/canvas.json      canvas index (artboard order + titles)
 *   wireframes/*.dc.html        one Design Component file per screen
 *   src/main, src/renderer      Electron main/preload and the renderer shell
 *   @fontsource-variable/*      Hanken Grotesk + Martian Mono (offline fonts)
 *
 * Output (gitignored):
 *   out/main/*                  copied as-is
 *   out/renderer/*              renderer shell + generated screens.js/json
 *   out/renderer/fonts/*        woff2 files + fonts.css
 *
 * The wireframes are compiled ahead of time so the renderer never needs
 * `eval`/`new Function` (strict CSP, see src/renderer/index.html).
 */
import { cpSync, existsSync, mkdirSync, readdirSync, readFileSync, rmSync, writeFileSync } from "node:fs";
import { createRequire } from "node:module";
import path from "node:path";
import { fileURLToPath } from "node:url";

const APP_DIR = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");

// Tags of the design format this runtime does not implement. Failing the
// build is better than shipping a screen that silently renders blank.
const UNSUPPORTED_TAGS = ["dc-import", "x-import"];

/** Pull a single capture group out of `text`, or throw with context. */
function mustMatch(re, text, what, file) {
	const m = re.exec(text);
	if (!m) throw new Error(`${file}: missing ${what}`);
	return m[1];
}

/**
 * Compile one `.dc.html` source into a screen definition.
 * Exported for the unit tests.
 */
export function compileScreen(file, source, canvasTitle) {
	for (const tag of UNSUPPORTED_TAGS) {
		if (source.includes(`<${tag}`)) throw new Error(`${file}: <${tag}> is not supported by the click-dummy runtime`);
	}
	const docTitle = mustMatch(/<title>([\s\S]*?)<\/title>/i, source, "<title>", file).trim();
	const body = mustMatch(/<x-dc>([\s\S]*?)<\/x-dc>/i, source, "<x-dc> body", file);
	const script = mustMatch(
		/<script[^>]*type="text\/x-dc"[^>]*>([\s\S]*?)<\/script>/i,
		source,
		"x-dc logic script",
		file,
	);
	if (!/class\s+Component\s+extends\s+DCLogic/.test(script)) {
		throw new Error(`${file}: logic script must declare "class Component extends DCLogic"`);
	}

	// <helmet> carries page-level CSS and the Google Fonts <link>. Only the
	// <style> blocks are kept: fonts ship inside the app (no network).
	const helmet = /<helmet>([\s\S]*?)<\/helmet>/i.exec(body);
	const style = helmet ? [...helmet[1].matchAll(/<style>([\s\S]*?)<\/style>/gi)].map((m) => m[1].trim()).join("\n") : "";
	const markup = helmet ? body.replace(helmet[0], "") : body;

	// <sc-for>/<sc-if> become <template> elements: the HTML parser keeps a
	// <template> wherever it appears (also inside <tbody>), whereas an
	// unknown element there would be foster-parented out of the table.
	const template = markup
		.replace(/<sc-(for|if)\b/g, '<template data-sc="$1"')
		.replace(/<\/sc-(for|if)>/g, "</template>")
		.trim();

	return {
		file,
		id: file.replace(/\.dc\.html$/, ""),
		title: canvasTitle || docTitle,
		docTitle,
		style,
		template,
		script: script.trim(),
	};
}

/** Serialise compiled screens into a classic script for the renderer. */
export function emitScreensJs(screens) {
	const parts = [
		"/* Generated by scripts/build_screens.mjs from wireframes/*.dc.html - do not edit. */",
		'"use strict";',
	];
	for (const s of screens) {
		const meta = JSON.stringify({ file: s.file, id: s.id, title: s.title, docTitle: s.docTitle, style: s.style, template: s.template });
		// The logic class is wrapped in a factory so `DCLogic` is injected by
		// the runtime and the class stays local to its screen.
		parts.push(`DCRuntime.register(${meta}, function (DCLogic) {\n${s.script}\nreturn Component;\n});`);
	}
	return `${parts.join("\n\n")}\n`;
}

/** Copy the variable fonts and alias their family names to the wireframes'. */
function buildFonts(outDir) {
	const require = createRequire(path.join(APP_DIR, "package.json"));
	const fonts = [
		{ pkg: "@fontsource-variable/hanken-grotesk", from: "Hanken Grotesk Variable", to: "Hanken Grotesk" },
		{ pkg: "@fontsource-variable/martian-mono", from: "Martian Mono Variable", to: "Martian Mono" },
	];
	const fontDir = path.join(outDir, "fonts");
	mkdirSync(fontDir, { recursive: true });
	const css = [];
	for (const f of fonts) {
		const pkgDir = path.dirname(require.resolve(`${f.pkg}/package.json`));
		const name = f.pkg.split("/")[1];
		cpSync(path.join(pkgDir, "files"), path.join(fontDir, name), { recursive: true });
		const index = readFileSync(path.join(pkgDir, "index.css"), "utf8")
			.replaceAll(`'${f.from}'`, `'${f.to}'`)
			.replaceAll("./files/", `./${name}/`);
		css.push(`/* ${f.pkg} (SIL OFL 1.1) */\n${index}`);
		const license = path.join(pkgDir, "LICENSE");
		if (existsSync(license)) cpSync(license, path.join(fontDir, name, "LICENSE"));
	}
	writeFileSync(path.join(fontDir, "fonts.css"), css.join("\n"));
}

/**
 * Artboard titles are numbered ("1 · Chat ...", "8 · Composer menus") but
 * the canvas lays them out spatially, so `order` is not the reading order.
 * When every title carries a number, sort by it (menu + Cmd+N follow it);
 * otherwise keep the canvas order. The first screen is the start screen.
 */
export function sortByNumber(screens) {
	const num = (s) => {
		const m = /^(\d+)\s*·/.exec(s.title);
		return m ? Number(m[1]) : null;
	};
	if (!screens.every((s) => num(s) !== null)) return screens;
	return [...screens].sort((a, b) => num(a) - num(b));
}

/** Full build: wireframes -> out/renderer/screens.js, plus static copies. */
export function build({ appDir = APP_DIR, withFonts = true } = {}) {
	const wireDir = path.join(appDir, "wireframes");
	const outDir = path.join(appDir, "out");
	const canvas = JSON.parse(readFileSync(path.join(wireDir, "canvas.json"), "utf8"));
	const order = Array.isArray(canvas.order) ? canvas.order : Object.keys(canvas.boards || {});
	// Artboards present on disk but missing from `order` still ship, last.
	const onDisk = readdirSync(wireDir).filter((f) => f.endsWith(".dc.html"));
	const files = [...order.filter((f) => onDisk.includes(f)), ...onDisk.filter((f) => !order.includes(f)).sort()];

	const screens = sortByNumber(
		files.map((f) => compileScreen(f, readFileSync(path.join(wireDir, f), "utf8"), canvas.boards?.[f]?.title)),
	);

	rmSync(outDir, { recursive: true, force: true });
	cpSync(path.join(appDir, "src", "main"), path.join(outDir, "main"), { recursive: true });
	cpSync(path.join(appDir, "src", "renderer"), path.join(outDir, "renderer"), { recursive: true });
	writeFileSync(path.join(outDir, "renderer", "screens.js"), emitScreensJs(screens));
	const index = { title: canvas.title || "Wireframes", screens: screens.map((s) => ({ file: s.file, title: s.title })) };
	writeFileSync(path.join(outDir, "renderer", "screens.json"), `${JSON.stringify(index, null, 2)}\n`);
	if (withFonts) buildFonts(path.join(outDir, "renderer"));
	return { screens, outDir };
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
	const { screens, outDir } = build();
	console.log(`click-dummy: compiled ${screens.length} screens into ${path.relative(process.cwd(), outDir) || "."}`);
}
